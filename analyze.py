RNG = np.random.RandomState(0)
INTER = ["self_teacher", "dml", "agree_only", "challenge"]
ROWS = ["solo", "ensemble_of_solo", "pooled_small", "pooled_big"] + INTER
LABEL = {"solo": "solo (mean of A, B)", "ensemble_of_solo": "ensemble of solo A+B",
         "pooled_small": "pooled labels, small", "pooled_big": "pooled labels, big",
         "self_teacher": "self-teacher (control)", "dml": "mutual (uniform)",
         "agree_only": "mutual, agreement-weighted", "challenge": "mutual, challenge-weighted"}
INTRO = """# Results summary

Two small networks (A and B) learn modular addition, `(a + b) mod 53`. Each one gets labels for a *different*
slice of the data. They can also see a shared pool of inputs with no labels, and learn from each other's
predictions on it. The question: does that interaction give them something neither has alone?

The tables further down are generated by `analyze.py` from the raw runs in `results/`. This part is the short version.

## What happened, in plain words

1. **The pre-registered setting (18% labeled per model) is a null.** Every model, alone or interacting, scores 0% on
   test. Two models that know nothing can't teach each other anything. Pooling both label sets does get somewhere
   (75% small model, 93% wider model), so the task is learnable. The interaction itself was sanity-checked with an
   oracle peer (a peer that knows the true labels of the shared inputs), which did learn, so the null is real and
   not a bug.

2. **Just above the learning threshold (30% labeled per model), interaction works very well.** I added this setting
   *after* seeing result 1, so it is exploratory, not confirmatory. On a random split, one model alone reaches 32.7%,
   two models averaged without talking reach 43.1%, and mutual learning reaches 99.7% (6 seeds, gap CI
   [+62, +72] points over solo). Pooled labels reach 100%, so interaction recovers essentially all of what pooling the
   labels gives, but does not beat it.

3. **It needs different data histories.** If both models get the *same* labeled set (only the init differs), mutual
   learning does nothing (21.3% vs 27.5% with no interaction). With different labeled sets it reaches 99.7%.

4. **It is not just extra training.** A solo model trained 4x longer ends at 22.1%, no better than at 6000 steps.
   A model distilling from a lagged copy of itself ends at 2.0%.

5. **Region split (each model sees labels from a different part of the input space).** Mutual learning reaches
   99.8-100%. The non-interacting ensemble reaches 92.0%, so interaction still adds about +8 points
   (CI [+2.8, +14.7]), and each model gets near-perfect on the *other* model's region (99.6%, vs 0.0% alone).

6. **Weighting the mutual loss toward agreement or toward disagreement ("challenge") makes no detectable
   difference.** All gaps are within noise.

7. **The two models converge.** Prediction disagreement drops from about 91% (solo) to under 1% after interaction.
   They end up nearly the same model, so this is knowledge transfer, not lasting diversity.

## How much to trust this

- Toy task, small MLPs, 4-6 seeds per setting. The bootstrap intervals are crude.
- The pre-registered prediction failed. The positive result lives in a setting chosen afterwards, and the mutual
  learning settings (loss weight, warm-up) were tuned there. Read it as "the effect exists in a narrow band near the
  threshold", not "interaction beats one model in general".
- Pooled labels were never beaten. The finding is about moving knowledge between models through unlabeled
  inputs, not about getting more than the data contains.
- A gap is called REAL only if its 95% bootstrap CI over seeds excludes 0 and the gap is at least 3 points (decided
  in PREREG.md before any run). "not established" means the data can't say, not that the effect is zero.

---

# Full results (auto-generated)

Metric: test accuracy at the final training step.
"""

REGNAME = {"P": "P (pre-registered, 18% labeled per model)", "T": "T (post-hoc, 30% labeled per model)"}


def load(reg, mode):
    fs = sorted(glob.glob(f"results/raw_{reg}_{mode}_*.json"), key=lambda f: int(re.findall(r"_(\d+)\.json", f)[0]))
    return [json.load(open(f)) for f in fs]


def val(r, c, kind="test"):
    if c == "ensemble_of_solo":
        return r["solo"]["ens_test"]
    x = r[c]
    if "M" in x:
        return x["M"][kind]
    return (x["A"][kind] + x["B"][kind]) / 2


def boot(d, n=10000):
    d = np.asarray(d)
    m = d[RNG.randint(0, len(d), (n, len(d)))].mean(1)
    return d.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5)


def verdict(d):
    m, lo, hi = boot(d)
    ok = (lo > 0 or hi < 0) and abs(m) >= 0.03
    return m, lo, hi, ("REAL" if ok else "not established")


def table(runs):
    out = ["| condition | mean test acc | per-seed range |", "|---|---|---|"]
    for c in ROWS:
        v = np.array([val(r, c) for r in runs])
        out.append(f"| {LABEL[c]} | {100*v.mean():.1f}% | {100*v.min():.1f}-{100*v.max():.1f}% |")
    return out


def comparisons(runs):
    pairs = [("H1", "dml", "solo"), ("H1", "dml", "ensemble_of_solo"), ("H1", "dml", "self_teacher"),
             ("H1", "challenge", "solo"), ("H1", "challenge", "ensemble_of_solo"), ("H1", "challenge", "self_teacher"),
             ("H2", "challenge", "dml"), ("H2", "challenge", "agree_only"),
             ("H3", "dml", "pooled_big"), ("H3", "agree_only", "pooled_big"), ("H3", "challenge", "pooled_big")]
    out = ["| hyp | comparison | mean gap (pts) | 95% CI | verdict |", "|---|---|---|---|---|"]
    for h, a, b in pairs:
        d = np.array([val(r, a) - val(r, b) for r in runs])
        m, lo, hi, v = verdict(d)
        out.append(f"| {h} | {LABEL[a]} - {LABEL[b]} | {100*m:+.1f} | [{100*lo:+.1f}, {100*hi:+.1f}] | {v} |")
    return out


def diversity(runs):
    out = ["| condition | CKA(A,B) on Test | A/B prediction disagreement on Test |", "|---|---|---|"]
    for c in ["solo"] + INTER:
        ck = np.mean([r[c]["cka"] for r in runs])
        dg = np.mean([r[c]["disagree"] for r in runs])
        out.append(f"| {LABEL.get(c, c)} | {ck:.3f} | {100*dg:.1f}% |")
    return out


def retention(runs):
    def own(r, c):
        return (r[c]["A"]["test_r0"] + r[c]["B"]["test_r1"]) / 2

    def other(r, c):
        return (r[c]["A"]["test_r1"] + r[c]["B"]["test_r0"]) / 2
    out = ["| condition | own-region acc | other-region acc | own-region change vs solo (pts, 95% CI) |", "|---|---|---|---|"]
    for c in ["solo"] + INTER:
        o = np.array([own(r, c) for r in runs])
        t = np.array([other(r, c) for r in runs])
        if c == "solo":
            ch = "-"
        else:
            m, lo, hi = boot(o - np.array([own(r, "solo") for r in runs]))
            ch = f"{100*m:+.1f} [{100*lo:+.1f}, {100*hi:+.1f}]"
        out.append(f"| {LABEL.get(c, c)} | {100*o.mean():.1f}% | {100*t.mean():.1f}% | {ch} |")
    return out


def fig_bars(runs, reg, mode):
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
    grey, blue, orange = "#9a9992", "#2a78d6", "#eb6834"
    col = {"solo": grey, "ensemble_of_solo": grey, "self_teacher": grey, "pooled_small": blue, "pooled_big": blue,
           "dml": orange, "agree_only": orange, "challenge": orange}
    short = {"solo": "solo", "ensemble_of_solo": "ensemble\n(no talk)", "self_teacher": "self-\nteacher",
             "pooled_small": "pooled\nsmall", "pooled_big": "pooled\nbig", "dml": "mutual\nuniform",
             "agree_only": "mutual\nagree", "challenge": "mutual\nchallenge"}
    for i, c in enumerate(ROWS):
        v = np.array([val(r, c) for r in runs]) * 100
        ax.bar(i, v.mean(), width=0.62, color=col[c], zorder=2)
        ax.scatter(np.full(len(v), i), v, s=14, color="#0b0b0b", zorder=3)
        ax.text(i, min(max(v.max(), v.mean()) + 2.5, 108), f"{v.mean():.0f}", ha="center", va="bottom", fontsize=8, color="#0b0b0b")
    ax.set_xticks(range(len(ROWS)))
    ax.set_xticklabels([short[c] for c in ROWS], fontsize=8, color="#52514e")
    ax.set_ylabel("test accuracy (%) at final step", fontsize=9, color="#52514e")
    ax.set_ylim(0, 112)
    ax.grid(axis="y", color="#e7e6e2", lw=0.6, zorder=0)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.set_title(f"Regime {reg}, {mode} split: dots are individual seeds (n={len(runs)})", fontsize=10, loc="left")
    fig.tight_layout()
    p = f"results/fig_bars_{reg}_{mode}.png"
    fig.savefig(p)
    plt.close(fig)
    return p


def fig_curves(runs, reg, mode):
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
    spec = [("solo", "solo", "#9a9992", "-"), ("self_teacher", "self-teacher", "#9a9992", "--"),
            ("pooled_small", "pooled small", "#e87ba4", "-"), ("dml", "mutual uniform", "#2a78d6", "-"),
            ("agree_only", "mutual agree", "#eb6834", "-"), ("challenge", "mutual challenge", "#1baf7a", "-")]
    for c, lab, colr, ls in spec:
        H = [r[c]["hist"] for r in runs]
        t = [h[0] for h in H[0]]
        y = np.mean([[np.mean(h[1]) for h in hh] for hh in H], 0) * 100
        ax.plot(t, y, color=colr, ls=ls, lw=2, label=lab)
    ax.set_xlabel("training step", fontsize=9, color="#52514e")
    ax.set_ylabel("mean test accuracy (%)", fontsize=9, color="#52514e")
    ax.grid(color="#e7e6e2", lw=0.6)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.legend(frameon=False, fontsize=8, loc="center right")
    ax.set_title(f"Regime {reg}, {mode} split: accuracy over training (mean of seeds)", fontsize=10, loc="left")
    fig.tight_layout()
    p = f"results/fig_curves_{reg}_{mode}.png"
    fig.savefig(p)
    plt.close(fig)
    return p



def extra_section():
    fs = sorted(glob.glob("results/extra_T_*.json"), key=lambda f: int(re.findall(r"_(\d+)\.json", f)[0]))
    if not fs:
        return []
    ex = [json.load(open(f)) for f in fs]
    main = load("T", "random")[:len(ex)]
    pm = lambda r, c: (r[c]["A"]["test"] + r[c]["B"]["test"]) / 2
    ss = np.array([pm(r, "solo_same") for r in ex]); ds = np.array([pm(r, "dml_same") for r in ex])
    dd = np.array([pm(r, "dml") for r in main])
    out = ["## Extra control (regime T, random split): does the peer need a DIFFERENT data history?", "",
           "Both models get the *same* 30% labeled set (S_A), only the init differs; same distillation on U as 'mutual (uniform)'.", "",
           "| condition | mean test acc | per-seed range |", "|---|---|---|"]
    for lab, v in [("same data, no interaction", ss), ("same data, mutual (uniform)", ds), ("different data, mutual (uniform)", dd)]:
        out.append(f"| {lab} | {100*v.mean():.1f}% | {100*v.min():.1f}-{100*v.max():.1f}% |")
    m, lo, hi, v = verdict(dd - ds)
    out += ["", f"different-data minus same-data (both mutual): {100*m:+.1f} pts, 95% CI [{100*lo:+.1f}, {100*hi:+.1f}] -> {v}", ""]
    return out

def long_section():
    out = []
    for reg in ("T", "P"):
        fs = sorted(glob.glob(f"results/long_{reg}_*.json"), key=lambda f: int(re.findall(r"_(\d+)\.json", f)[0]))
        if not fs:
            continue
        lg = [json.load(open(f)) for f in fs]
        main = load(reg, "random")[:len(lg)]
        pm = lambda r, c: (r[c]["A"]["test"] + r[c]["B"]["test"]) / 2
        sl = np.array([pm(r, "solo_long") for r in lg]); s6 = np.array([pm(r, "solo") for r in main])
        dm = np.array([pm(r, "dml") for r in main])
        peak = np.array([max(np.mean(h[1]) for h in r["solo_long"]["hist"]) for r in lg])
        out += [f"## Control: solo trained 4x longer (24000 steps) - regime {REGNAME[reg]}, random split, {len(lg)} seeds", "",
                "| condition | mean test acc (final step) | per-seed range |", "|---|---|---|"]
        for lab, v in [("solo, 6000 steps", s6), ("solo, 24000 steps", sl), ("mutual (uniform), 6000 steps", dm)]:
            out.append(f"| {lab} | {100*v.mean():.1f}% | {100*v.min():.1f}-{100*v.max():.1f}% |")
        m, lo, hi, v = verdict(dm - sl)
        out += ["", f"highest accuracy any solo_long run reached at any logged step (mean over seeds): {100*peak.mean():.1f}%",
                f"mutual(6000 steps) minus solo(24000 steps): {100*m:+.1f} pts, 95% CI [{100*lo:+.1f}, {100*hi:+.1f}] -> {v}", ""]
    return out

if __name__ == "__main__":
    md = INTRO.split("\n")
    for reg in ("P", "T"):
        for mode in ("random", "region"):
            runs = load(reg, mode)
            if not runs:
                continue
            md += [f"## Regime {REGNAME[reg]} - {mode} split - {len(runs)} seeds", ""]
            md += table(runs) + [""] + ["### Pre-registered comparisons", ""] + comparisons(runs) + [""]
            md += ["### Diversity (H4)", ""] + diversity(runs) + [""]
            if mode == "region":
                md += ["### Retention and transfer (H5)", ""] + retention(runs) + [""]
            fig_bars(runs, reg, mode)
            fig_curves(runs, reg, mode)
    md += extra_section()
    md += long_section()
    open("results/summary.md", "w").write("\n".join(md))
    print("\n".join(md))