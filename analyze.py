"""Summarize results/raw_*.json into results/summary.md and figures.
Decision rule (PREREG): a gap counts only if the 95% bootstrap CI over seeds excludes 0
AND |mean gap| >= 3 accuracy points. Metric = test accuracy at the final step."""
